void OLED_ShowString(uint8_t line, char *str) {
    uint8_t i, col;
    if (line > 7) line = 7;
    OLED_WriteCmd(0xB0 + line);
    OLED_WriteCmd(0x00);
    OLED_WriteCmd(0x10);
    for (i = 0; str[i] != '\0' && i < 16; i++) {
        uint8_t c = str[i] - 32;
        if (c > 94) c = 0;
        for (col = 0; col < 6; col++) {
            OLED_WriteData(Font6x8[c][col]);
        }
        OLED_WriteData(0x00);
    }
}

