void OLED_ShowFloat(uint8_t line, float num, uint8_t decimals) {
    char buf[20];
    if (decimals == 2) {
        sprintf(buf, "%.2f", num);
    } else if (decimals == 3) {
        sprintf(buf, "%.3f", num);
    } else if (decimals == 4) {
        sprintf(buf, "%.4f", num);
    } else {
        sprintf(buf, "%.1f", num);
    }
    OLED_ShowString(line, buf);
}